SELECT A.CATEGORY, SUM(SUM) AS TOTAL_SALES
    FROM BOOK A
    JOIN (
        SELECT BOOK_ID, SUM(SALES) AS SUM
            FROM BOOK_SALES
            WHERE '2022-01-01' <= SALES_DATE AND SALES_DATE < '2022-02-01'
            GROUP BY BOOK_ID    
    ) B
    ON A.BOOK_ID = B.BOOK_ID
    GROUP BY A.CATEGORY
    ORDER BY A.CATEGORY
